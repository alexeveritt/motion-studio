import { lstat, mkdir, readFile } from "node:fs/promises";
import path from "node:path";
import { writeFileAtomic } from "./fs-store.ts";
import { slugify } from "./slug.ts";
import { toRepoRelative } from "./repo.ts";
import type { WorkspaceService } from "./workspace.ts";

export type RegistryResult = {
  /** Absolute path of the generated module. */
  file: string;
  changed: boolean;
  /** compositionId -> repository-relative entry file. */
  entries: Record<string, string>;
};

/** The generated registry for a workspace lives in the rebuildable cache, one file per workspace root. */
export function registryFile(workspace: WorkspaceService): string {
  const key = slugify(toRepoRelative(workspace.repoRoot, workspace.workspaceRoot)) || "workspace";
  return workspace.policy.resolve(workspace.cacheRoot, "registry", `${key}.ts`);
}

/**
 * Generate the composition registry: an explicit allowlist mapping each
 * validated production's compositionId to a static import of its entry file.
 * Productions with no entry file yet are left out. The file is rewritten only
 * when its content changes, so the dev server is not needlessly reloaded.
 */
export async function writeRegistry(workspace: WorkspaceService): Promise<RegistryResult> {
  const file = registryFile(workspace);
  const catalog = await workspace.scan();
  const entries: Record<string, string> = {};
  const lines: string[] = [];

  for (const project of catalog.projects) {
    for (const campaign of project.campaigns) {
      for (const production of campaign.productions) {
        const record = production.record;
        const dir = path.join(workspace.repoRoot, ...production.path.split("/"));
        const entry = workspace.policy.resolveRelative(dir, record.files.entry);
        const stats = await lstat(entry).catch(() => undefined);
        if (!stats?.isFile()) continue;

        let specifier = path.relative(path.dirname(file), entry).split(path.sep).join("/");
        if (!specifier.startsWith(".")) specifier = `./${specifier}`;
        const relativeEntry = toRepoRelative(workspace.repoRoot, entry);
        entries[record.compositionId] = relativeEntry;
        lines.push(
          `  ${JSON.stringify(record.compositionId)}: {`,
          `    productionId: ${JSON.stringify(record.id)},`,
          `    entry: ${JSON.stringify(relativeEntry)},`,
          `    load: () => import(${JSON.stringify(specifier)}),`,
          `  },`,
        );
      }
    }
  }

  const source = `// Generated by Motion Studio from validated production records. Do not edit.
// Workspace: ${catalog.workspacePath}
import type { Registry } from "@motion-studio/motion-runtime";

export const registry: Registry = {
${lines.join("\n")}
};
`;
  const previous = await readFile(file, "utf8").catch(() => undefined);
  if (previous !== source) {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFileAtomic(file, source);
  }
  return { file, changed: previous !== source, entries };
}
