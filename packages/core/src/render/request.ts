import type { ProductionFormat } from "../schemas/production.ts";
import type { MediaRenderOptions } from "./options.ts";

/**
 * The immutable job request handed to the render worker as a file. Every
 * path is absolute and was resolved by the controller through the path
 * policy; the worker never derives paths itself.
 */
export type RenderRequest = {
  schemaVersion: 1;
  renderId: string;
  kind: "render" | "poster" | "frames";
  productionId: string;
  compositionId: string;
  profileId: string;
  format: ProductionFormat;
  options: MediaRenderOptions;
  posterFrame: number;
  sampleFrames: number[];
  inputProps: Record<string, unknown>;
  bundleEntry: string;
  publicDir: string;
  bundleDir: string;
  smokeDir: string;
  /** Video and poster for renders; poster for poster jobs; frames for golden-frame jobs. */
  outputs: { video?: string; poster?: string; frames?: { frame: number; path: string }[] };
  /** Per-frame delayRender timeout. */
  frameTimeoutMs: number;
};

/** One line of the worker's stdout protocol. */
export type WorkerMessage =
  | { type: "phase"; phase: RenderPhase }
  | {
      type: "progress";
      phase: RenderPhase;
      progress: number;
      renderedFrames?: number;
      encodedFrames?: number;
    }
  | { type: "log"; message: string }
  | { type: "frame-error"; frame: number; message: string }
  | { type: "done" }
  | { type: "error"; code: string; message: string };

export type RenderPhase =
  | "queued"
  | "preflight"
  | "browser"
  | "bundling"
  | "checking"
  | "rendering"
  | "poster"
  | "frames"
  | "finalising"
  | "done";

/**
 * The bundle entry for one production: registers a single Remotion
 * composition whose size, FPS and duration come from production.json, with
 * the composition wrapped in the render-side asset resolver (public folder).
 */
export function renderEntrySource(options: {
  entryImport: string;
  entryLabel: string;
  compositionId: string;
  format: ProductionFormat;
}): string {
  const { width, height, fps, durationInFrames } = options.format;
  return `// Generated by Motion Studio for one render job. Do not edit.
import { AssetResolverProvider, validateComposition } from "@motion-studio/motion-runtime";
import type { ComponentType } from "react";
import { Composition, registerRoot, staticFile } from "remotion";
import * as entryModule from ${JSON.stringify(options.entryImport)};

const composition = validateComposition(entryModule, ${JSON.stringify(options.compositionId)}, ${JSON.stringify(options.entryLabel)});
const Component = composition.Component as ComponentType<Record<string, unknown>>;

function WithRuntime(props: Record<string, unknown>) {
  return (
    <AssetResolverProvider resolve={(scope, name) => staticFile(\`assets/\${scope}/\${name}\`)}>
      <Component {...props} />
    </AssetResolverProvider>
  );
}

function Root() {
  return (
    <Composition
      id={${JSON.stringify(options.compositionId)}}
      component={WithRuntime}
      width={${width}}
      height={${height}}
      fps={${fps}}
      durationInFrames={${durationInFrames}}
      defaultProps={composition.defaultProps}
    />
  );
}

registerRoot(Root);
`;
}
