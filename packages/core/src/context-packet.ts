export type PacketOptions = {
  /** Base URL of the running studio, for the link back to the production page. */
  studioUrl?: string;
};

type Located = { project: ProjectEntry; campaign: CampaignEntry; production: ProductionEntry };

async function locateProduction(
  workspace: WorkspaceService,
  productionId: string,
): Promise<Located> {
  const catalog = await workspace.scan();
  for (const project of catalog.projects) {
    for (const campaign of project.campaigns) {
      const production = campaign.productions.find((entry) => entry.record.id === productionId);
      if (production) return { project, campaign, production };
    }
  }
  throw new MotionStudioError("NOT_FOUND", "The production was not found");
}

/**
 * Assemble the Claude-ready context packet for a production (spec section
 * 8.3). It is generated on demand from the files on disk and never stored, so
 * it cannot drift from them.
 */
export async function buildContextPacket(
  workspace: WorkspaceService,
  assets: AssetLibrary,
  productionId: string,
  options: PacketOptions = {},
): Promise<string> {
  const { project, campaign, production } = await locateProduction(workspace, productionId);
  const record = production.record;
  const profile = workspace.settings.renderProfiles.find(
    (p) => p.id === record.defaultRenderProfileId,
  );
  const doc = async (scope: "project" | "production", id: string, kind: string) =>
    (await workspace.readDocument(scope, id, kind)).content.trim();

  const [prompt, brief, context, brand] = await Promise.all([
    doc("production", record.id, "prompt"),
    doc("production", record.id, "brief"),
    doc("project", project.record.id, "context"),
    doc("project", project.record.id, "brand"),
  ]);
  const listings = await Promise.all([
    assets.list("production", record.id),
    assets.list("campaign", campaign.record.id),
    assets.list("project", project.record.id),
    assets.list("brand", project.record.id),
  ]);
  const sourceFiles = (await workspace.listFiles("production", record.id)).filter((file) => {
    const relative = file.slice(production.path.length + 1);
    return relative.startsWith("src/") || relative.startsWith("tests/");
  });

  const { width, height, fps, durationInFrames } = record.format;
  const studioLink = options.studioUrl
    ? `${options.studioUrl}/projects/${project.record.slug}/campaigns/${campaign.record.slug}/productions/${record.slug}`
    : undefined;

  const sections = [
    `# Context packet: ${record.title}`,
    `Generated by Motion Studio from the files in \`${production.path}/\`. Regenerate it after changing the brief, prompt or assets.`,

    `## Request\n\n${fence(prompt || "_prompt.md is empty._")}`,

    `## Edit boundary

- Work only inside \`${production.path}/\`, chiefly \`src/\` and \`tests/\`.
- Change shared code in \`packages/motion-runtime\` only when it is clearly needed by more than one production, and say why.
- Do not edit \`production.json\` by hand; change format, duration, poster frame and status in Motion Studio.
- Do not commit, push, or change branches.`,

    `## Repository

- \`apps/studio/\`: Astro management UI (the studio). Not part of the composition.
- \`packages/core/\`: schemas and filesystem services.
- \`packages/motion-runtime/\`: Remotion root, composition registry and shared motion helpers.
- \`workspace/projects/<project>/campaigns/<campaign>/productions/<production>/\`: one folder per production.
- Plain files are the source of truth; there is no database.`,

    `## Composition contract

\`${record.files.entry}\` exports:

\`\`\`ts
export const composition: MotionStudioComposition = {
  id: "${record.compositionId}",
  Component: YourComponent,
  defaultProps: {},
};
\`\`\`

\`MotionStudioComposition\` comes from \`packages/motion-runtime\`. Width, height, FPS and duration come from \`production.json\`; do not hard-code them.

Assets, fonts and props:

- Reach assets only through \`useAsset("<scope>:<stored name>")\` from \`@motion-studio/motion-runtime\`, where scope is \`production\`, \`campaign\`, \`project\` or \`brand\`, e.g. \`useAsset("brand:logo.svg")\`. Only registered assets (those with a \`.asset.json\` sidecar) resolve. Use Remotion's \`<Img>\`, \`<Audio>\` and \`<Video>\` with the returned URL.
- Load fonts from font assets with \`useLocalFont({ family, url: useAsset("brand:font.woff2") })\`.
- Production-specific values (destination URLs, dates, copy variants) go in \`props.json\` in the production folder; it is merged over \`defaultProps\` for preview and render.
- \`SafeArea\`, \`seededRange\` and \`seededInt\` are also exported by the runtime.

Determinism rules:

- Derive all animation from \`useCurrentFrame()\`, FPS, props and local assets.
- Use a seeded helper for randomness. Never read the clock or the network.
- Load fonts from local files. Give locale-sensitive formatting an explicit locale and time zone.
- Pass dates and destination URLs as props, never hard-coded live values.`,

    `## Production

| Field | Value |
| --- | --- |
| Title | ${cell(record.title)} |
| Composition ID | \`${record.compositionId}\` |
| Status | ${record.status} |
| Format | ${width} × ${height}, ${fps} fps |
| Duration | ${durationInFrames} frames (${formatDurationLabel(durationInFrames, fps)}); last frame is ${durationInFrames - 1} |
| Poster frame | ${record.posterFrame} |
| Tags | ${record.tags.join(", ") || "none"} |
| Production ID | \`${record.id}\` |
${studioLink ? `| Studio page | ${studioLink} |\n` : ""}
${record.description ? `${record.description}\n` : ""}`,

    `## Render profile: ${profile?.name ?? record.defaultRenderProfileId}

${profile ? fence(JSON.stringify(profile, null, 2), "json") : `Profile \`${record.defaultRenderProfileId}\` is not defined in settings.`}`,

    `## Project: ${project.record.name}

${project.record.description || "No description."}
${project.record.sourceRepository ? `\nProduct source repository (reference only, do not modify): \`${project.record.sourceRepository.path}\`\n` : ""}`,

    `## Campaign: ${campaign.record.name}

- Objective: ${campaign.record.objective || "not set"}
- Audience: ${campaign.record.audience.join("; ") || "not set"}
- Key messages: ${campaign.record.keyMessages.join("; ") || "not set"}
- Channels: ${campaign.record.channels.join("; ") || "not set"}`,

    `## Project context\n\n${fence(context || "_context.md is empty._")}`,
    `## Brand guidance\n\n${fence(brand || "_brand.md is empty._")}`,
    `## Production brief\n\n${fence(brief || "_brief.md is empty._")}`,

    `## Assets

Paths are repository-relative. Reference files by their stored name; never modify or overwrite them.

${listings.map(assetTable).join("\n\n")}`,

    `## Existing source files

${sourceFiles.length > 0 ? sourceFiles.map((file) => `- \`${file}\``).join("\n") : "None yet. Create the entry file first."}`,

    `## Commands

\`\`\`sh
pnpm check                 # type checks and framework checks
pnpm test                  # unit and integration tests
pnpm validate:workspace    # validate every record, sidecar and asset hash
pnpm render -- ${record.id} --profile draft     # quick render; standard or high-quality for approval
pnpm poster -- ${record.id} --frame ${record.posterFrame}   # render one poster frame
pnpm -s context-packet -- ${record.id}   # print this packet again
\`\`\`

Preview the production in the studio (\`pnpm dev\`)${studioLink ? `: ${studioLink}?tab=preview` : ", Preview tab"}. The Preview tab's **Check source** button type-checks this production's \`src/\` and lists errors with file and line.`,
  ];

  return `${sections
    .join("\n\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim()}\n`;
}

const SCOPE_LABELS: Record<AssetListing["scope"], string> = {
  production: "Production assets",
  campaign: "Campaign assets",
  project: "Project assets",
  brand: "Brand assets",
};

function assetTable(listing: AssetListing): string {
  const heading = `### ${SCOPE_LABELS[listing.scope]} (\`${listing.folder}/\`)`;
  if (listing.assets.length === 0 && listing.unregistered.length === 0)
    return `${heading}\n\nNone.`;
  const rows = listing.assets.map(({ record, path: file, status }) => {
    const size = record.width && record.height ? `${record.width}×${record.height}` : "";
    const notes = [
      record.altText && `Alt: ${record.altText}`,
      record.source && `Source: ${record.source}`,
      record.licenceNotes && `Licence: ${record.licenceNotes}`,
      status !== "ok" && `**${status.toUpperCase()}**`,
    ]
      .filter(Boolean)
      .join(". ");
    return `| \`${file}\` | ${record.mimeType} | ${size} | ${formatBytes(record.bytes)} | \`${record.sha256.slice(0, 16)}…\` | ${cell(notes)} |`;
  });
  const unregistered = listing.unregistered.map(
    ({ path: file }) =>
      `| \`${file}\` | unregistered | | | | Not yet registered in Motion Studio |`,
  );
  return `${heading}

| Path | Type | Size | Bytes | SHA-256 | Notes |
| --- | --- | --- | --- | --- | --- |
${[...rows, ...unregistered].join("\n")}`;
}

/** Fence a document so its own headings and fences cannot break the packet structure. */
function fence(text: string, language = "markdown"): string {
  const longest = Math.max(2, ...[...text.matchAll(/`{3,}/g)].map((match) => match[0].length));
  const marker = "`".repeat(longest + 1);
  return `${marker}${language}\n${text}\n${marker}`;
}

function cell(text: string): string {
  return text.replaceAll("|", "\\|").replaceAll("\n", " ");
}

export type PromptCandidate = {
  /** Repository-relative path of the saved candidate, under .motion-studio/tmp. */
  candidatePath: string;
  candidate: string;
  current: DocumentContent;
  diff: DiffLine[];
};

/**
 * Regenerate prompt.md from the template without touching the saved prompt.
 * The candidate is written to a gitignored folder; the operator reviews the
 * diff and replaces the saved prompt deliberately with a normal document save.
 */
export async function createPromptCandidate(
  workspace: WorkspaceService,
  productionId: string,
): Promise<PromptCandidate> {
  const { project, campaign, production } = await locateProduction(workspace, productionId);
  const candidate = productionPromptTemplate(project.record, campaign.record, production.record);
  const current = await workspace.readDocument("production", productionId, "prompt");
  const dir = workspace.policy.resolve(
    workspace.tmpRoot,
    "prompt-candidates",
    `${production.record.slug}-${productionId.slice(-8)}`,
  );
  await mkdir(dir, { recursive: true });
  const stamp = formatStamp(workspace.now());
  let file = path.join(dir, `${stamp}.md`);
  for (let attempt = 2; ; attempt++) {
    try {
      await writeFileExclusive(file, candidate);
      break;
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== "EEXIST" || attempt > 50) throw error;
      file = path.join(dir, `${stamp}-${attempt}.md`);
    }
  }
  return {
    candidatePath: toRepoRelative(workspace.repoRoot, file),
    candidate,
    current,
    diff: lineDiff(current.content, candidate),
  };
}
